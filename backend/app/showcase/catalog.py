def _medicine_rows() -> list[CatalogSeedRow]:
    rows: list[CatalogSeedRow] = []
    for raw_drug in DRUGS:
        drug = cast(dict[str, object], raw_drug)
        variants = cast(list[tuple[str, str, str]], drug["variants"])
        for dosage, pack_size, price in variants:
            rows.append(
                CatalogSeedRow(
                    brand_name=str(drug["brand"]),
                    inn=str(drug["inn"]),
                    manufacturer=str(drug["manufacturer"]),
                    form=str(drug["form"]),
                    dosage=dosage,
                    pack_size=pack_size,
                    atx_code=str(drug["atx"]),
                    dispensing_type=str(drug["dispensing"]),
                    storage_type=str(drug["storage"]),
                    category=str(drug["category"]),
                    price=Decimal(price),
                    master_linked=True,
                )
            )
    return rows


def _goods_rows() -> list[CatalogSeedRow]:
    rows: list[CatalogSeedRow] = []
    for name, category, form, variants in _GOODS_FAMILIES:
        for manufacturer in _GOODS_MANUFACTURERS:
            for pack_size, price in variants:
                rows.append(
                    CatalogSeedRow(
                        brand_name=name,
                        inn=None,
                        manufacturer=manufacturer,
                        form=form,
                        dosage=None,
                        pack_size=pack_size,
                        atx_code=None,
                        dispensing_type="otc",
                        storage_type="normal",
                        category=category,
                        price=Decimal(price),
                        master_linked=False,
                    )
                )
    return rows


def showcase_catalog_rows() -> list[CatalogSeedRow]:
    rows = [*_medicine_rows(), *_goods_rows()]
    keys = [row.stable_key for row in rows]
    if len(keys) != len(set(keys)):
        raise RuntimeError("Showcase catalogue contains duplicate stable keys")
    return rows
