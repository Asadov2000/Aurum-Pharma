@dataclass(frozen=True, slots=True)
class CatalogSeedRow:
    brand_name: str
    inn: str | None
    manufacturer: str
    form: str
    dosage: str | None
    pack_size: str
    atx_code: str | None
    dispensing_type: str
    storage_type: str
    category: str
    price: Decimal
    master_linked: bool

    @property
    def stable_key(self) -> str:
        return "|".join(
            (
                self.brand_name,
                self.dosage or "",
                self.form,
                self.manufacturer,
                self.pack_size,
            )
        )


